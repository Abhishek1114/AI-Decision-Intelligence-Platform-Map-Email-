"""
Phase 6 — event_details.py

Source events are currently cited in reports as bare hashes
(e.g. [81478f78faf488a336876db2399947b7]) — meaningless to a human
reader without a separate Cypher lookup. This module fetches the real
GlobalEvent data behind those IDs so:
  1. The LLM can be given titles to weave into prose naturally, and
  2. A deterministic (non-LLM-generated) reference table can be appended
     to the report, guaranteeing the title shown is accurate regardless
     of what the model actually wrote — traceability that doesn't depend
     on trusting the model's transcription.
"""

from neo4j import Session

FETCH_EVENT_DETAILS = """
MATCH (e:GlobalEvent)
WHERE e.event_id IN $event_ids
RETURN e.event_id AS event_id,
       e.title AS title,
       e.severity AS severity,
       e.category AS category,
       e.source_tier AS source_tier
"""


def fetch_event_details(session: Session, event_ids: list[str]) -> dict[str, dict]:
    """
    Returns {event_id: {title, severity, category, source_tier}}.
    Any event_id with no matching GlobalEvent is simply absent from the
    result — callers should handle a missing key rather than assume
    every id resolves (e.g. if a GlobalEvent were ever purged).
    """
    if not event_ids:
        return {}

    result = session.run(FETCH_EVENT_DETAILS, {"event_ids": list(set(event_ids))})
    return {
        record["event_id"]: {
            "title": record["title"],
            "severity": record["severity"],
            "category": record["category"],
            "source_tier": record["source_tier"],
        }
        for record in result
    }


def build_reference_table(event_details: dict[str, dict]) -> str:
    """
    Deterministic markdown table, NOT generated by the LLM — this is what
    actually guarantees the title shown matches the real GlobalEvent,
    independent of anything the model wrote in its narrative.
    """
    if not event_details:
        return ""

    lines = [
        "",
        "**SOURCE EVENT REFERENCE**",
        "",
        "| Event ID | Title | Severity | Category |",
        "|---|---|---|---|",
    ]
    for event_id, details in sorted(event_details.items()):
        lines.append(
            f"| {event_id} | {details.get('title', 'unknown')} "
            f"| {details.get('severity', 'unknown')} "
            f"| {details.get('category', 'unknown')} |"
        )
    return "\n".join(lines) + "\n"